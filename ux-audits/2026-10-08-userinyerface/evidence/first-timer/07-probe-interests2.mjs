// Probe 2: visual before/after of tapping "Ponies" on a 390 phone + event listeners around the list.
import { E, sleep, launch, newPage, go, game } from "./lib.mjs";
const browser = await launch();
const page = await newPage(browser);
await go(page, "https://userinyerface.com/game.html");
await sleep(2600);
await page.evaluate(() => document.querySelector(".cookies button")?.click());
await page.evaluate((g) => { eval(g).currentPageIndex = 1; }, game);
await sleep(800);
console.log("card says:", await page.$eval(".page-indicator", (e) => e.innerText));
await page.evaluate(() => document.querySelector(".help-form__send-to-bottom-button").click());
await sleep(500);
const state = () => page.evaluate(() => [...document.querySelectorAll(".avatar-and-interests__interests-list__item")].map((e) => (e.querySelector("input").checked ? "x" : "_") + e.innerText.trim()).join(" "));
const h = await page.evaluateHandle(() => document.querySelector("#interest_ponies").closest("label").querySelector(".checkbox__box"));
await h.evaluate((x) => x.scrollIntoView({ block: "center", behavior: "instant" })); await sleep(300);
await page.screenshot({ path: E + "s2-390-before-tap-ponies.png" });
const bb = await h.boundingBox();
const cdp = await page.createCDPSession();
const { result } = await cdp.send("Runtime.evaluate", { expression: "document.querySelector('#interest_ponies')" });
const { listeners } = await cdp.send("DOMDebugger.getEventListeners", { objectId: result.objectId, depth: -1 });
console.log("listeners on ponies input:", listeners.map((l) => l.type));
const doc = await cdp.send("Runtime.evaluate", { expression: "document" });
console.log("document listeners:", (await cdp.send("DOMDebugger.getEventListeners", { objectId: doc.result.objectId })).listeners.map((l) => l.type));
const win = await cdp.send("Runtime.evaluate", { expression: "window" });
console.log("window listeners:", (await cdp.send("DOMDebugger.getEventListeners", { objectId: win.result.objectId })).listeners.map((l) => l.type));
await page.evaluate(() => { window.__ev = []; for (const t of ["click", "change", "input"]) document.addEventListener(t, (e) => window.__ev.push(t + ":" + (e.target.id || e.target.className)), true); });
console.log("before:", await state());
await page.touchscreen.tap(bb.x + bb.width / 2, bb.y + bb.height / 2); await sleep(500);
console.log("after tap ponies:", await state(), await page.evaluate(() => window.__ev));
await page.screenshot({ path: E + "s2-390-after-tap-ponies.png" });
await page.evaluate(() => (window.__ev = []));
const w = await page.evaluateHandle(() => [...document.querySelectorAll(".avatar-and-interests__interests-list__item span")].find((e) => e.innerText.trim() === "Purple"));
const wb = await w.boundingBox();
await page.touchscreen.tap(wb.x + wb.width / 2, wb.y + wb.height / 2); await sleep(500);
console.log("after tap word Purple:", await state(), await page.evaluate(() => window.__ev));
await browser.close();
